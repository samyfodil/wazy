// testdata holds two sets of WIT inputs, each run under three feature sets:
// none, WithFeatures("active") and WithAllFeatures.
//
//   - testdata/wit-parser/ui: wit-parser's own UI tests, from
//     bytecodealliance/wasm-tools at a pinned commit (see its README). Each
//     ships its result with "active" enabled: a .wit.json of the resolved
//     packages, or a .wit.result error under parse-fail/.
//   - testdata/cases: hand-written inputs for what those do not cover.
//
// testdata/oracle holds what wit-parser (wasm-tools 1.262.0; see
// gen-oracle.sh) makes of both under the other feature sets, and of the
// hand-written inputs under all three.
//
// The UI tests and the oracle are fetched and generated by
// `make build.component_testdata`, not committed, so they are embedded
// through testdata itself: a checkout without them still builds.
//
//go:embed testdata
var testdata embed.FS

// fetched skips t when dir, which `make build.component_testdata` makes, is
// not there.
func fetched(t *testing.T, dir string) {
	t.Helper()
	if _, err := fs.Stat(testdata, dir); err != nil {
		// Skipping is right for a working tree that has not fetched it; in CI
		// it would mean the suite silently never ran, so the jobs set this.
		if os.Getenv("WAZY_SPECTEST_REQUIRE_CASES") != "" {
			t.Fatalf("no %s and WAZY_SPECTEST_REQUIRE_CASES is set: `make build.component_testdata` must run first (%v)", dir, err)
		}
		t.Skipf("no %s: run `make build.component_testdata` to fetch it (%v)", dir, err)
	}
}

var featureSets = map[string][]Option{
	"none":   nil,
	"active": {WithFeatures("active")},
	"all":    {WithAllFeatures()},
}

// skipped are the inputs this package cannot read at all, and why.
var skipped = map[string]string{
	// wit-parser also reads a dep that is a WIT package encoded as a
	// component, in the binary format (deps/e.wasm) or the text format
	// (deps/d.wat); ParseFS reads only .wit deps.
	"kinds-of-deps": "deps encoded as components (.wasm, .wat)",
}

// TestWitParserUI parses each of wit-parser's inputs -- a .wit file, or a
// directory with deps/ -- under each feature set and compares the result
// with wit-parser's: the same packages, interfaces, types, funcs and world
// items, or an error where wit-parser has one.
func TestWitParserUI(t *testing.T) {
	fetched(t, "testdata/wit-parser/ui")
	runOracle(t, "testdata/wit-parser/ui", true)
}

// TestCases is TestWitParserUI for the hand-written inputs.
func TestCases(t *testing.T) {
	runOracle(t, "testdata/cases", false)
}

func runOracle(t *testing.T, dir string, shipped bool) {
	fetched(t, "testdata/oracle")
	entries, err := fs.ReadDir(testdata, dir)
	if err != nil {
		t.Fatal(err)
	}
	ran := 0
	for _, e := range entries {
		name := strings.TrimSuffix(e.Name(), ".wit")
		if e.Name() == "parse-fail" || !e.IsDir() && name == e.Name() {
			continue
		}
		for _, set := range []string{"none", "active", "all"} {
			ran++
			t.Run(name+"."+set, func(t *testing.T) {
				if why, ok := skipped[name]; ok {
					t.Skip(why)
				}
				got, gotErr := parseInput(t, path.Join(dir, e.Name()), e.IsDir(), featureSets[set]...)
				var wantJSON []byte
				var wantErr string
				if shipped && set == "active" {
					wantJSON = readTestdata(t, path.Join(dir, name+".wit.json"))
				} else {
					wantJSON, wantErr = oracle(t, name+"."+set)
				}
				switch {
				case wantErr != "":
					if gotErr == nil {
						t.Fatalf("parsed; wit-parser rejects it: %s", wantErr)
					}
					if !strings.Contains(gotErr.Error(), wantErr) {
						t.Fatalf("error %q\nwant it to contain %q", gotErr, wantErr)
					}
				case gotErr != nil:
					t.Fatalf("wit-parser accepts it: %v", gotErr)
				default:
					if g, w := summarize(got), summarizeJSON(t, wantJSON); !slices.Equal(g, w) {
						t.Fatalf("got\n\t%s\nwant\n\t%s", strings.Join(g, "\n\t"), strings.Join(w, "\n\t"))
					}
				}
			})
		}
	}
	if ran == 0 {
		t.Fatalf("no inputs in %s", dir)
	}
}

func readTestdata(t *testing.T, p string) []byte {
	b, err := fs.ReadFile(testdata, p)
	if err != nil {
		t.Fatal(err)
	}
	return b
}

// oracle reads wit-parser's result for one input and feature set: its
// resolved JSON, or its error.
func oracle(t *testing.T, key string) (jsonSrc []byte, errLine string) {
	base := "testdata/oracle/" + key
	if b, err := fs.ReadFile(testdata, base+".err"); err == nil {
		return nil, strings.TrimSpace(string(b))
	}
	b, err := fs.ReadFile(testdata, base+".json")
	if err != nil {
		t.Fatalf("no oracle result for %s (run `make build.component_testdata`): %v", key, err)
	}
	return b, ""
}

// parseInput parses one of wit-parser's inputs: a directory as ParseFS reads
// it, or a single file as Parse does.
func parseInput(t *testing.T, p string, isDir bool, opts ...Option) (*Package, error) {
	if isDir {
		sub, err := fs.Sub(testdata, p)
		if err != nil {
			t.Fatal(err)
		}
		return ParseFS(sub, ".", opts...)
	}
	src, err := fs.ReadFile(testdata, p)
	if err != nil {
		t.Fatal(err)
	}
	return Parse(path.Base(p), string(src), opts...)
}

// summarize lists what a parse resolved, one sorted line per package,
// interface and world, in the form summarizeJSON gives wit-parser's.
func summarize(root *Package) []string {
	var out []string
	for _, p := range append([]*Package{root}, root.Deps...) {
		out = append(out, "package "+p.Name)
		for _, i := range p.Interfaces {
			types := append(slices.Clone(i.scope.order), i.scope.used...)
			var funcs []string
			for _, f := range i.Funcs {
				funcs = append(funcs, f.Name)
			}
			out = append(out, ifaceLine(p.Name, ast.LastSegment(i.Name), types, funcs))
		}
		for _, w := range p.Worlds {
			var imports, exports []string
			for _, it := range w.Imports {
				imports = append(imports, it.Name)
			}
			for _, it := range w.Exports {
				exports = append(exports, it.Name)
			}
			out = append(out, worldLine(p.Name, w.Name, imports, exports))
		}
	}
	slices.Sort(out)
	return out
}

func ifaceLine(pkg, name string, types, funcs []string) string {
	slices.Sort(types)
	slices.Sort(funcs)
	return fmt.Sprintf("interface %s/%s types=%v funcs=%v", pkg, name, types, funcs)
}

func worldLine(pkg, name string, imports, exports []string) string {
	slices.Sort(imports)
	slices.Sort(exports)
	return fmt.Sprintf("world %s/%s imports=%v exports=%v", pkg, name, imports, exports)
}

// witJSON is the part of wit-parser's resolved JSON that summarizeJSON reads.
type witJSON struct {
	Worlds []struct {
		Name    string                  `json:"name"`
		Imports map[string]witWorldItem `json:"imports"`
		Exports map[string]witWorldItem `json:"exports"`
		Package int                     `json:"package"`
	} `json:"worlds"`
	Interfaces []struct {
		Name      *string                    `json:"name"`
		Types     map[string]int             `json:"types"`
		Functions map[string]json.RawMessage `json:"functions"`
		Package   *int                       `json:"package"`
	} `json:"interfaces"`
	Packages []struct {
		Name       string         `json:"name"`
		Interfaces map[string]int `json:"interfaces"`
		Worlds     map[string]int `json:"worlds"`
	} `json:"packages"`
}

type witWorldItem struct {
	Interface *struct {
		ID int `json:"id"`
	} `json:"interface"`
	Type *int `json:"type"`
}

// summarizeJSON lists wit-parser's resolved packages as summarize does ours.
// A world's types are not world items here, so they are skipped; an
// interface it imports by name is listed by its qualified name.
func summarizeJSON(t *testing.T, src []byte) []string {
	var d witJSON
	if err := json.Unmarshal(src, &d); err != nil {
		t.Fatal(err)
	}
	var out []string
	for _, p := range d.Packages {
		out = append(out, "package "+p.Name)
		for name, id := range p.Interfaces {
			i := d.Interfaces[id]
			var types, funcs []string
			for ty := range i.Types {
				types = append(types, ty)
			}
			for f := range i.Functions {
				funcs = append(funcs, f)
			}
			out = append(out, ifaceLine(p.Name, name, types, funcs))
		}
		for name, id := range p.Worlds {
			w := d.Worlds[id]
			names := func(items map[string]witWorldItem) []string {
				var out []string
				for key, it := range items {
					switch {
					case it.Type != nil:
						continue
					case it.Interface != nil && strings.HasPrefix(key, "interface-"):
						i := d.Interfaces[it.Interface.ID]
						key = qualify(d.Packages[*i.Package].Name, *i.Name)
					}
					out = append(out, key)
				}
				return out
			}
			out = append(out, worldLine(p.Name, name, names(w.Imports), names(w.Exports)))
		}
	}
	slices.Sort(out)
	return out
}

// resultContext is the context wit-parser's test runner wraps an error of
// a directory input in, which is not the error's own.
var resultContext = regexp.MustCompile(`^(failed to resolve directory while parsing WIT for path \[[^]]*\]: |failed to parse package: [^:]*: |failed to parse dependency directory: [^:]*: )+`)

// wantError is the first line of a .wit.result, the error itself.
func wantError(result string) string {
	line, _, _ := strings.Cut(result, "\n")
	return strings.ReplaceAll(resultContext.ReplaceAllString(line, ""), "tests/ui/parse-fail/", "")
}

// TestWitParserParseFail runs wit-parser's own failing inputs: each must
// fail here too, with wit-parser's text.
func TestWitParserParseFail(t *testing.T) {
	const dir = "testdata/wit-parser/ui/parse-fail"
	fetched(t, dir)
	entries, err := fs.ReadDir(testdata, dir)
	if err != nil {
		t.Fatal(err)
	}
	ran := 0
	for _, e := range entries {
		if strings.HasSuffix(e.Name(), ".result") {
			continue
		}
		ran++
		t.Run(e.Name(), func(t *testing.T) {
			result, err := fs.ReadFile(testdata, path.Join(dir, strings.TrimSuffix(e.Name(), ".wit")+".wit.result"))
			if err != nil {
				t.Fatal(err)
			}
			want := wantError(string(result))
			_, gotErr := parseInput(t, path.Join(dir, e.Name()), e.IsDir(), WithFeatures("active"))
			switch {
			case gotErr == nil:
				t.Fatalf("parsed; wit-parser rejects it: %s", want)
			case !strings.Contains(gotErr.Error(), want):
				t.Fatalf("error %q\nwant it to contain %q", gotErr, want)
			}
		})
	}
	if ran == 0 {
		t.Fatal("no inputs")
	}
}
